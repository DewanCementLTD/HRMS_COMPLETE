-- ============================================================================
-- Training Management (L&D) — schema
-- Plan: docs/Training_Management_Plan.md
--
-- Every table is scoped by COMPC (= HR_EMP_MASTER.UNIT_ID / EMPLOYEE.COMPC).
-- Employees are keyed by EMPCODE (= EMPLOYEE.EMP_PK = CARD_NO, e.g. '100511.1').
-- PKs come from one sequence per table, like RECRUITMENT_JOBS_SEQ.
-- FY_YEAR is the starting year of a July–June fiscal year (2026 = Jul 2026–Jun 2027).
--
-- Run once with: node scripts/run_training_ddl.mjs
-- ============================================================================

CREATE SEQUENCE HR_TRAINING_CATEGORY_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_CATEGORY (
  CATEGORY_ID   NUMBER        PRIMARY KEY,
  COMPC         NUMBER        NOT NULL,
  NAME          VARCHAR2(100) NOT NULL,
  IS_ACTIVE     CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY    VARCHAR2(30),
  CREATED_AT    DATE          DEFAULT SYSDATE,
  UPDATED_BY    VARCHAR2(30),
  UPDATED_AT    DATE
);
CREATE UNIQUE INDEX HR_TRAINING_CATEGORY_UK ON HR_TRAINING_CATEGORY (COMPC, UPPER(NAME));

CREATE SEQUENCE HR_TRAINER_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINER (
  TRAINER_ID    NUMBER        PRIMARY KEY,
  COMPC         NUMBER        NOT NULL,
  TRAINER_TYPE  CHAR(1)       NOT NULL CHECK (TRAINER_TYPE IN ('I','E')),  -- I = internal employee, E = external
  EMPCODE       VARCHAR2(30),                                              -- internal trainer
  NAME          VARCHAR2(100) NOT NULL,
  ORGANIZATION  VARCHAR2(150),
  PHONE         VARCHAR2(30),
  EMAIL         VARCHAR2(100),
  EXPERTISE     VARCHAR2(300),
  DEFAULT_RATE  NUMBER(12,2),
  IS_ACTIVE     CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY    VARCHAR2(30),
  CREATED_AT    DATE          DEFAULT SYSDATE,
  UPDATED_BY    VARCHAR2(30),
  UPDATED_AT    DATE
);
CREATE INDEX HR_TRAINER_COMPC_IX ON HR_TRAINER (COMPC);

CREATE SEQUENCE HR_TRAINING_COURSE_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_COURSE (
  COURSE_ID       NUMBER        PRIMARY KEY,
  COMPC           NUMBER        NOT NULL,
  COURSE_CODE     VARCHAR2(20)  NOT NULL,
  TITLE           VARCHAR2(200) NOT NULL,
  CATEGORY_ID     NUMBER        REFERENCES HR_TRAINING_CATEGORY (CATEGORY_ID),
  TRAINING_TYPE   VARCHAR2(20)  DEFAULT 'TECHNICAL' NOT NULL
                  CHECK (TRAINING_TYPE IN ('TECHNICAL','SOFT_SKILL','COMPLIANCE','SAFETY','OTHER')),
  DEFAULT_MODE    VARCHAR2(10)  DEFAULT 'PHYSICAL' NOT NULL CHECK (DEFAULT_MODE IN ('PHYSICAL','ONLINE')),
  DURATION_HRS    NUMBER(6,2),
  DESCRIPTION     VARCHAR2(2000),
  CERT_REQUIRED   CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (CERT_REQUIRED IN ('Y','N')),
  PASS_PCT        NUMBER(5,2)   DEFAULT 70 NOT NULL,
  MIN_ATTEND_PCT  NUMBER(5,2)   DEFAULT 80 NOT NULL,
  IS_ACTIVE       CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY      VARCHAR2(30),
  CREATED_AT      DATE          DEFAULT SYSDATE,
  UPDATED_BY      VARCHAR2(30),
  UPDATED_AT      DATE
);
CREATE UNIQUE INDEX HR_TRAINING_COURSE_UK ON HR_TRAINING_COURSE (COMPC, COURSE_CODE);

CREATE SEQUENCE HR_TRAINING_BUDGET_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_BUDGET (
  BUDGET_ID     NUMBER        PRIMARY KEY,
  COMPC         NUMBER        NOT NULL,
  FY_YEAR       NUMBER(4)     NOT NULL,
  DEPT_NO       NUMBER,                        -- NULL = company-level budget
  AMOUNT        NUMBER(14,2)  NOT NULL CHECK (AMOUNT >= 0),
  REMARKS       VARCHAR2(300),
  CREATED_BY    VARCHAR2(30),
  CREATED_AT    DATE          DEFAULT SYSDATE,
  UPDATED_BY    VARCHAR2(30),
  UPDATED_AT    DATE
);
CREATE UNIQUE INDEX HR_TRAINING_BUDGET_UK ON HR_TRAINING_BUDGET (COMPC, FY_YEAR, NVL(DEPT_NO, -1));

CREATE SEQUENCE HR_TRAINING_SESSION_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_SESSION (
  SESSION_ID     NUMBER        PRIMARY KEY,
  COMPC          NUMBER        NOT NULL,
  SESSION_CODE   VARCHAR2(20)  NOT NULL,
  COURSE_ID      NUMBER        NOT NULL REFERENCES HR_TRAINING_COURSE (COURSE_ID),
  TRAINER_ID     NUMBER        REFERENCES HR_TRAINER (TRAINER_ID),
  MODE_TYPE      VARCHAR2(10)  DEFAULT 'PHYSICAL' NOT NULL CHECK (MODE_TYPE IN ('PHYSICAL','ONLINE')),
  VENUE          VARCHAR2(200),
  ONLINE_LINK    VARCHAR2(500),
  START_DATE     DATE          NOT NULL,
  END_DATE       DATE          NOT NULL,
  TIME_FROM      VARCHAR2(5),                  -- 'HH24:MI'
  TIME_TO        VARCHAR2(5),
  TOTAL_HOURS    NUMBER(6,2),
  CAPACITY       NUMBER(5)     DEFAULT 20 NOT NULL CHECK (CAPACITY > 0),
  DEPT_NO        NUMBER,                       -- department that owns the cost (optional)
  FY_YEAR        NUMBER(4)     NOT NULL,
  TRAINER_COST   NUMBER(14,2)  DEFAULT 0 NOT NULL,
  VENUE_COST     NUMBER(14,2)  DEFAULT 0 NOT NULL,
  MATERIAL_COST  NUMBER(14,2)  DEFAULT 0 NOT NULL,
  OTHER_COST     NUMBER(14,2)  DEFAULT 0 NOT NULL,
  STATUS         VARCHAR2(12)  DEFAULT 'PLANNED' NOT NULL
                 CHECK (STATUS IN ('PLANNED','OPEN','IN_PROGRESS','COMPLETED','CANCELLED')),
  REMARKS        VARCHAR2(1000),
  COMPLETED_AT   DATE,
  CREATED_BY     VARCHAR2(30),
  CREATED_AT     DATE          DEFAULT SYSDATE,
  UPDATED_BY     VARCHAR2(30),
  UPDATED_AT     DATE,
  CHECK (END_DATE >= START_DATE)
);
CREATE UNIQUE INDEX HR_TRAINING_SESSION_UK ON HR_TRAINING_SESSION (COMPC, SESSION_CODE);
CREATE INDEX HR_TRAINING_SESSION_IX ON HR_TRAINING_SESSION (COMPC, START_DATE);

CREATE SEQUENCE HR_TRAINING_REQUEST_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_REQUEST (
  REQUEST_ID       NUMBER        PRIMARY KEY,
  COMPC            NUMBER        NOT NULL,
  BRNCH            NUMBER,
  EMPCODE          VARCHAR2(30)  NOT NULL,
  SOURCE           VARCHAR2(10)  DEFAULT 'EMPLOYEE' NOT NULL CHECK (SOURCE IN ('EMPLOYEE','HOD','HR')),
  REQUESTED_BY     VARCHAR2(30)  NOT NULL,
  COURSE_ID        NUMBER        REFERENCES HR_TRAINING_COURSE (COURSE_ID),
  REQUESTED_TOPIC  VARCHAR2(300),
  REASON           VARCHAR2(1000),
  PRIORITY         VARCHAR2(6)   DEFAULT 'MEDIUM' NOT NULL CHECK (PRIORITY IN ('LOW','MEDIUM','HIGH')),
  PREFERRED_FROM   DATE,
  PREFERRED_TO     DATE,
  HOD1_MNO         VARCHAR2(30),
  HOD1_FLAG        CHAR(1)       CHECK (HOD1_FLAG IN ('Y','N')),
  HOD1_DATE        DATE,
  HOD1_NAME        VARCHAR2(100),
  HOD1_REMARKS     VARCHAR2(500),
  HOD2_MNO         VARCHAR2(30),
  HOD2_FLAG        CHAR(1)       CHECK (HOD2_FLAG IN ('Y','N')),
  HOD2_DATE        DATE,
  HOD2_NAME        VARCHAR2(100),
  HOD2_REMARKS     VARCHAR2(500),
  HR_FLAG          CHAR(1)       CHECK (HR_FLAG IN ('Y','N')),
  HR_DATE          DATE,
  HR_NAME          VARCHAR2(100),
  HR_REMARKS       VARCHAR2(500),
  STATUS           VARCHAR2(14)  DEFAULT 'PENDING_HOD1' NOT NULL
                   CHECK (STATUS IN ('PENDING_HOD1','PENDING_HOD2','PENDING_HR','APPROVED','BOOKED',
                                     'COMPLETED','REJECTED','CANCELLED')),
  SESSION_ID       NUMBER        REFERENCES HR_TRAINING_SESSION (SESSION_ID),
  CREATED_BY       VARCHAR2(30),
  CREATED_AT       DATE          DEFAULT SYSDATE,
  UPDATED_BY       VARCHAR2(30),
  UPDATED_AT       DATE,
  CHECK (COURSE_ID IS NOT NULL OR REQUESTED_TOPIC IS NOT NULL)
);
CREATE INDEX HR_TRAINING_REQUEST_EMP_IX ON HR_TRAINING_REQUEST (EMPCODE);
CREATE INDEX HR_TRAINING_REQUEST_ST_IX ON HR_TRAINING_REQUEST (COMPC, STATUS);

CREATE SEQUENCE HR_TRAINING_PARTICIPANT_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_PARTICIPANT (
  PARTICIPANT_ID  NUMBER        PRIMARY KEY,
  SESSION_ID      NUMBER        NOT NULL REFERENCES HR_TRAINING_SESSION (SESSION_ID),
  COMPC           NUMBER        NOT NULL,
  EMPCODE         VARCHAR2(30)  NOT NULL,
  REQUEST_ID      NUMBER        REFERENCES HR_TRAINING_REQUEST (REQUEST_ID),  -- NULL when HR assigned directly
  STATUS          VARCHAR2(10)  DEFAULT 'BOOKED' NOT NULL
                  CHECK (STATUS IN ('BOOKED','COMPLETED','FAILED','NO_SHOW','WITHDRAWN')),
  ATTEND_PCT      NUMBER(5,2),
  PRE_SCORE_PCT   NUMBER(5,2),
  POST_SCORE_PCT  NUMBER(5,2),
  PASSED          CHAR(1)       CHECK (PASSED IN ('Y','N')),
  RETEST_ALLOWED  NUMBER(2)     DEFAULT 0 NOT NULL,   -- extra post-test attempts HR has granted
  CERT_NO         VARCHAR2(40),
  CERT_ISSUED_AT  DATE,
  CREATED_BY      VARCHAR2(30),
  CREATED_AT      DATE          DEFAULT SYSDATE,
  UPDATED_BY      VARCHAR2(30),
  UPDATED_AT      DATE
);
CREATE UNIQUE INDEX HR_TRAINING_PARTICIPANT_UK ON HR_TRAINING_PARTICIPANT (SESSION_ID, EMPCODE);
CREATE INDEX HR_TRAINING_PARTICIPANT_EMP_IX ON HR_TRAINING_PARTICIPANT (EMPCODE);
CREATE UNIQUE INDEX HR_TRAINING_CERT_UK ON HR_TRAINING_PARTICIPANT (CERT_NO);

CREATE TABLE HR_TRAINING_ATTENDANCE (
  PARTICIPANT_ID  NUMBER        NOT NULL REFERENCES HR_TRAINING_PARTICIPANT (PARTICIPANT_ID),
  SESSION_DATE    DATE          NOT NULL,
  STATUS          CHAR(1)       NOT NULL CHECK (STATUS IN ('P','A','L')),
  HOURS           NUMBER(5,2),
  UPDATED_BY      VARCHAR2(30),
  UPDATED_AT      DATE          DEFAULT SYSDATE,
  CONSTRAINT HR_TRAINING_ATTENDANCE_PK PRIMARY KEY (PARTICIPANT_ID, SESSION_DATE)
);

CREATE SEQUENCE HR_TRAINING_TEST_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_TEST (
  TEST_ID         NUMBER        PRIMARY KEY,
  COMPC           NUMBER        NOT NULL,
  COURSE_ID       NUMBER        NOT NULL REFERENCES HR_TRAINING_COURSE (COURSE_ID),
  TEST_KIND       VARCHAR2(4)   NOT NULL CHECK (TEST_KIND IN ('PRE','POST')),
  TITLE           VARCHAR2(200) NOT NULL,
  TIME_LIMIT_MIN  NUMBER(4)     DEFAULT 30 NOT NULL,
  PASS_PCT        NUMBER(5,2),                          -- NULL = use the course's PASS_PCT
  SHUFFLE         CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (SHUFFLE IN ('Y','N')),
  IS_ACTIVE       CHAR(1)       DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY      VARCHAR2(30),
  CREATED_AT      DATE          DEFAULT SYSDATE,
  UPDATED_BY      VARCHAR2(30),
  UPDATED_AT      DATE
);
CREATE UNIQUE INDEX HR_TRAINING_TEST_UK ON HR_TRAINING_TEST (COURSE_ID, TEST_KIND);

CREATE SEQUENCE HR_TRAINING_QUESTION_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_QUESTION (
  QUESTION_ID    NUMBER         PRIMARY KEY,
  TEST_ID        NUMBER         NOT NULL REFERENCES HR_TRAINING_TEST (TEST_ID),
  SEQ            NUMBER(4)      DEFAULT 0 NOT NULL,
  QUESTION_TEXT  VARCHAR2(1000) NOT NULL,
  OPT_A          VARCHAR2(500)  NOT NULL,
  OPT_B          VARCHAR2(500)  NOT NULL,
  OPT_C          VARCHAR2(500),
  OPT_D          VARCHAR2(500),
  CORRECT_OPT    CHAR(1)        NOT NULL CHECK (CORRECT_OPT IN ('A','B','C','D')),
  MARKS          NUMBER(5,2)    DEFAULT 1 NOT NULL CHECK (MARKS > 0),
  IS_ACTIVE      CHAR(1)        DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N'))
);
CREATE INDEX HR_TRAINING_QUESTION_IX ON HR_TRAINING_QUESTION (TEST_ID);

CREATE SEQUENCE HR_TRAINING_ATTEMPT_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_ATTEMPT (
  ATTEMPT_ID      NUMBER        PRIMARY KEY,
  TEST_ID         NUMBER        NOT NULL REFERENCES HR_TRAINING_TEST (TEST_ID),
  PARTICIPANT_ID  NUMBER        NOT NULL REFERENCES HR_TRAINING_PARTICIPANT (PARTICIPANT_ID),
  STARTED_AT      DATE          DEFAULT SYSDATE NOT NULL,
  DEADLINE_AT     DATE          NOT NULL,
  SUBMITTED_AT    DATE,
  SCORE           NUMBER(7,2),
  TOTAL           NUMBER(7,2),
  PCT             NUMBER(5,2),
  PASSED          CHAR(1)       CHECK (PASSED IN ('Y','N'))
);
CREATE INDEX HR_TRAINING_ATTEMPT_IX ON HR_TRAINING_ATTEMPT (PARTICIPANT_ID, TEST_ID);

CREATE TABLE HR_TRAINING_ANSWER (
  ATTEMPT_ID    NUMBER   NOT NULL REFERENCES HR_TRAINING_ATTEMPT (ATTEMPT_ID),
  QUESTION_ID   NUMBER   NOT NULL REFERENCES HR_TRAINING_QUESTION (QUESTION_ID),
  SELECTED_OPT  CHAR(1)  CHECK (SELECTED_OPT IN ('A','B','C','D')),
  IS_CORRECT    CHAR(1)  CHECK (IS_CORRECT IN ('Y','N')),
  CONSTRAINT HR_TRAINING_ANSWER_PK PRIMARY KEY (ATTEMPT_ID, QUESTION_ID)
);

CREATE SEQUENCE HR_TRAINING_FEEDBACK_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_FEEDBACK (
  FEEDBACK_ID     NUMBER        PRIMARY KEY,
  SESSION_ID      NUMBER        NOT NULL REFERENCES HR_TRAINING_SESSION (SESSION_ID),
  PARTICIPANT_ID  NUMBER        REFERENCES HR_TRAINING_PARTICIPANT (PARTICIPANT_ID),  -- NULL for trainer/HR feedback
  GIVEN_BY_TYPE   VARCHAR2(10)  NOT NULL CHECK (GIVEN_BY_TYPE IN ('EMPLOYEE','TRAINER','HR','MANAGER')),
  GIVEN_BY        VARCHAR2(30),
  RATING_CONTENT  NUMBER(1)     CHECK (RATING_CONTENT BETWEEN 1 AND 5),
  RATING_TRAINER  NUMBER(1)     CHECK (RATING_TRAINER BETWEEN 1 AND 5),
  RATING_OVERALL  NUMBER(1)     NOT NULL CHECK (RATING_OVERALL BETWEEN 1 AND 5),
  COMMENTS        VARCHAR2(1000),
  CREATED_AT      DATE          DEFAULT SYSDATE
);
-- One employee feedback per participant; trainer/HR rows (PARTICIPANT_ID NULL) are not indexed.
CREATE UNIQUE INDEX HR_TRAINING_FEEDBACK_UK ON HR_TRAINING_FEEDBACK (
  CASE WHEN PARTICIPANT_ID IS NOT NULL THEN SESSION_ID END, PARTICIPANT_ID);

CREATE SEQUENCE HR_TRAINING_LOG_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINING_LOG (
  LOG_ID     NUMBER         PRIMARY KEY,
  COMPC      NUMBER,
  ENTITY     VARCHAR2(12)   NOT NULL,     -- REQUEST / SESSION / PARTICIPANT / COURSE / ...
  ENTITY_ID  NUMBER         NOT NULL,
  ACTION     VARCHAR2(30)   NOT NULL,
  DETAILS    VARCHAR2(2000),              -- JSON: previous/new values, remarks
  ACTOR      VARCHAR2(30),
  ACTED_AT   DATE           DEFAULT SYSDATE NOT NULL
);
CREATE INDEX HR_TRAINING_LOG_IX ON HR_TRAINING_LOG (ENTITY, ENTITY_ID);

