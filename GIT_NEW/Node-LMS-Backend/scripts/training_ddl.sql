CREATE SEQUENCE HR_TRAINER_SLOT_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_TRAINER_SLOT (
  SLOT_ID     NUMBER        PRIMARY KEY,
  TRAINER_ID  NUMBER        NOT NULL REFERENCES HR_TRAINER (TRAINER_ID),
  SLOT_DATE   DATE          NOT NULL,
  TIME_FROM   VARCHAR2(5)   NOT NULL,
  TIME_TO     VARCHAR2(5)   NOT NULL,
  REMARKS     VARCHAR2(300),
  CREATED_AT  DATE          DEFAULT SYSDATE,
  CHECK (TIME_TO > TIME_FROM)
);
CREATE INDEX HR_TRAINER_SLOT_IX ON HR_TRAINER_SLOT (TRAINER_ID, SLOT_DATE);

