-- ============================================================================
-- Performance Appraisal — schema
-- BRD: "HRMS Learning & Development and Performance Appraisal.pdf" (§15–§33)
--
-- Conventions follow scripts/training_ddl.sql:
--   * every table is scoped by COMPC (= HR_EMP_MASTER.UNIT_ID)
--   * employees are keyed by EMPCODE (= EMPLOYEE.EMP_PK = CARD_NO)
--   * one <TABLE>_SEQ sequence per table
--   * FY_YEAR is the starting year of a July–June fiscal year
--
-- Approval chain per appraisal (missing levels are skipped):
--   reporting officer (HR_EMP_MASTER.RPT_OFFICER) → HOD1 → HOD2 → HR → management
--
-- Run once with: node scripts/run_appraisal_ddl.mjs  (idempotent, re-runnable)
-- ============================================================================

-- Rating bands (BRD §23). Seeded per company by the app the first time it is read.
CREATE SEQUENCE HR_APPR_RATING_SCALE_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_APPR_RATING_SCALE (
  SCALE_ID        NUMBER        PRIMARY KEY,
  COMPC           NUMBER        NOT NULL,
  MIN_SCORE       NUMBER(5,2)   NOT NULL,
  MAX_SCORE       NUMBER(5,2)   NOT NULL,
  LABEL           VARCHAR2(40)  NOT NULL,
  TARGET_PCT      NUMBER(5,2),                    -- bell curve: target share of employees in this band
  IS_DEVELOPMENT  CHAR(1)       DEFAULT 'N' NOT NULL CHECK (IS_DEVELOPMENT IN ('Y','N')),  -- band gets a development plan
  CREATED_BY      VARCHAR2(30),
  CREATED_AT      DATE          DEFAULT SYSDATE,
  UPDATED_BY      VARCHAR2(30),
  UPDATED_AT      DATE,
  CHECK (MAX_SCORE >= MIN_SCORE)
);
CREATE INDEX HR_APPR_RATING_SCALE_IX ON HR_APPR_RATING_SCALE (COMPC, MIN_SCORE);

CREATE SEQUENCE HR_KPI_MASTER_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_KPI_MASTER (
  KPI_ID        NUMBER         PRIMARY KEY,
  COMPC         NUMBER         NOT NULL,
  NAME          VARCHAR2(100)  NOT NULL,
  DESCRIPTION   VARCHAR2(1000),
  CATEGORY      VARCHAR2(50),
  MEASURE_TYPE  VARCHAR2(8)    DEFAULT 'RATING' NOT NULL CHECK (MEASURE_TYPE IN ('RATING','NUMBER','PCT')),
  IS_ACTIVE     CHAR(1)        DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY    VARCHAR2(30),
  CREATED_AT    DATE           DEFAULT SYSDATE,
  UPDATED_BY    VARCHAR2(30),
  UPDATED_AT    DATE
);
CREATE UNIQUE INDEX HR_KPI_MASTER_UK ON HR_KPI_MASTER (COMPC, UPPER(NAME));

CREATE SEQUENCE HR_COMPETENCY_MASTER_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_COMPETENCY_MASTER (
  COMPETENCY_ID  NUMBER         PRIMARY KEY,
  COMPC          NUMBER         NOT NULL,
  NAME           VARCHAR2(100)  NOT NULL,
  DESCRIPTION    VARCHAR2(1000),
  IS_ACTIVE      CHAR(1)        DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY     VARCHAR2(30),
  CREATED_AT     DATE           DEFAULT SYSDATE,
  UPDATED_BY     VARCHAR2(30),
  UPDATED_AT     DATE
);
CREATE UNIQUE INDEX HR_COMPETENCY_MASTER_UK ON HR_COMPETENCY_MASTER (COMPC, UPPER(NAME));

-- A template is picked per employee at launch: GRADE_CD match, then DESG_GRP, then IS_DEFAULT.
CREATE SEQUENCE HR_APPRAISAL_TEMPLATE_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_APPRAISAL_TEMPLATE (
  TEMPLATE_ID       NUMBER         PRIMARY KEY,
  COMPC             NUMBER         NOT NULL,
  NAME              VARCHAR2(100)  NOT NULL,
  DESCRIPTION       VARCHAR2(1000),
  DESG_GRP          VARCHAR2(10),                 -- HR_DESG.DESG_GRP filter (optional)
  GRADE_CD          VARCHAR2(10),                 -- HR_EMP_MASTER.GRADE_CD filter (optional)
  IS_DEFAULT        CHAR(1)        DEFAULT 'N' NOT NULL CHECK (IS_DEFAULT IN ('Y','N')),
  GOAL_WEIGHT_PCT   NUMBER(5,2)    DEFAULT 50 NOT NULL,
  KPI_WEIGHT_PCT    NUMBER(5,2)    DEFAULT 30 NOT NULL,
  COMP_WEIGHT_PCT   NUMBER(5,2)    DEFAULT 20 NOT NULL,
  USE_SELF_RATING   CHAR(1)        DEFAULT 'N' NOT NULL CHECK (USE_SELF_RATING IN ('Y','N')),  -- self rating counts when no reviewer rated
  IS_ACTIVE         CHAR(1)        DEFAULT 'Y' NOT NULL CHECK (IS_ACTIVE IN ('Y','N')),
  CREATED_BY        VARCHAR2(30),
  CREATED_AT        DATE           DEFAULT SYSDATE,
  UPDATED_BY        VARCHAR2(30),
  UPDATED_AT        DATE,
  CHECK (GOAL_WEIGHT_PCT + KPI_WEIGHT_PCT + COMP_WEIGHT_PCT = 100)
);
CREATE UNIQUE INDEX HR_APPRAISAL_TEMPLATE_UK ON HR_APPRAISAL_TEMPLATE (COMPC, UPPER(NAME));

CREATE SEQUENCE HR_APPRAISAL_TEMPLATE_ITEM_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_APPRAISAL_TEMPLATE_ITEM (
  ITEM_ID      NUMBER        PRIMARY KEY,
  TEMPLATE_ID  NUMBER        NOT NULL REFERENCES HR_APPRAISAL_TEMPLATE (TEMPLATE_ID),
  ITEM_TYPE    VARCHAR2(10)  NOT NULL CHECK (ITEM_TYPE IN ('KPI','COMPETENCY')),
  REF_ID       NUMBER        NOT NULL,             -- HR_KPI_MASTER.KPI_ID / HR_COMPETENCY_MASTER.COMPETENCY_ID
  WEIGHTAGE    NUMBER(5,2)   NOT NULL CHECK (WEIGHTAGE > 0),
  SEQ          NUMBER(4)     DEFAULT 0 NOT NULL
);
CREATE UNIQUE INDEX HR_APPRAISAL_TEMPLATE_ITEM_UK ON HR_APPRAISAL_TEMPLATE_ITEM (TEMPLATE_ID, ITEM_TYPE, REF_ID);

CREATE SEQUENCE HR_APPRAISAL_CYCLE_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_APPRAISAL_CYCLE (
  CYCLE_ID         NUMBER         PRIMARY KEY,
  COMPC            NUMBER         NOT NULL,
  NAME             VARCHAR2(100)  NOT NULL,
  CYCLE_TYPE       VARCHAR2(12)   DEFAULT 'ANNUAL' NOT NULL
                   CHECK (CYCLE_TYPE IN ('ANNUAL','HALF_YEARLY','QUARTERLY','PROBATION','CONFIRMATION')),
  FY_YEAR          NUMBER(4)      NOT NULL,
  PERIOD_FROM      DATE           NOT NULL,
  PERIOD_TO        DATE           NOT NULL,
  GOAL_DEADLINE    DATE,
  SELF_DEADLINE    DATE,
  REVIEW_DEADLINE  DATE,
  STATUS           VARCHAR2(8)    DEFAULT 'DRAFT' NOT NULL CHECK (STATUS IN ('DRAFT','ACTIVE','CLOSED')),
  REMARKS          VARCHAR2(1000),
  CREATED_BY       VARCHAR2(30),
  CREATED_AT       DATE           DEFAULT SYSDATE,
  UPDATED_BY       VARCHAR2(30),
  UPDATED_AT       DATE,
  CHECK (PERIOD_TO >= PERIOD_FROM)
);
CREATE INDEX HR_APPRAISAL_CYCLE_IX ON HR_APPRAISAL_CYCLE (COMPC, FY_YEAR);

-- Corporate / department goals HR pushes into every appraisal of a cycle.
