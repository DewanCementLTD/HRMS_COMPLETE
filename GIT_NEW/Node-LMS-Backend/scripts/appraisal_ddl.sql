-- One appraisal per employee per cycle.
--   STAGE: GOALS → GOALS_REVIEW → SELF → RPT → HOD1 → HOD2 → HR → MGMT → COMPLETED
CREATE SEQUENCE HR_APPRAISAL_MASTER_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_APPRAISAL_MASTER (
  APPRAISAL_ID     NUMBER          PRIMARY KEY,
  COMPC            NUMBER          NOT NULL,
  CYCLE_ID         NUMBER          NOT NULL REFERENCES HR_APPRAISAL_CYCLE (CYCLE_ID),
  EMPCODE          VARCHAR2(30)    NOT NULL,
  TEMPLATE_ID      NUMBER          NOT NULL REFERENCES HR_APPRAISAL_TEMPLATE (TEMPLATE_ID),
  BRNCH            NUMBER,
  DEPT_NO          VARCHAR2(10),
  DESG_CD          VARCHAR2(10),
  GRADE_CD         VARCHAR2(10),
  RPT_EMPCODE      VARCHAR2(30),                 -- approver snapshot at launch
  HOD1_MNO         VARCHAR2(30),
  HOD2_MNO         VARCHAR2(30),
  STAGE            VARCHAR2(12)    DEFAULT 'GOALS' NOT NULL
                   CHECK (STAGE IN ('GOALS','GOALS_REVIEW','SELF','RPT','HOD1','HOD2','HR','MGMT','COMPLETED','CANCELLED')),
  GOAL_REVIEWER    VARCHAR2(4)     CHECK (GOAL_REVIEWER IN ('RPT','HOD1','HOD2','HR')),
  ACHIEVEMENTS     VARCHAR2(4000),
  CHALLENGES       VARCHAR2(2000),
  SELF_COMMENTS    VARCHAR2(2000),
  SELF_SUBMITTED_AT DATE,
  SELF_SCORE       NUMBER(5,2),
  CALC_SCORE       NUMBER(5,2),
  HR_ADJ_SCORE     NUMBER(5,2),
  HR_ADJ_REASON    VARCHAR2(1000),
  FINAL_SCORE      NUMBER(5,2),
  FINAL_RATING     VARCHAR2(40),
  COMPLETED_AT     DATE,
  CREATED_BY       VARCHAR2(30),
  CREATED_AT       DATE            DEFAULT SYSDATE,
  UPDATED_BY       VARCHAR2(30),
  UPDATED_AT       DATE
);
CREATE UNIQUE INDEX HR_APPRAISAL_MASTER_UK ON HR_APPRAISAL_MASTER (CYCLE_ID, EMPCODE);
CREATE INDEX HR_APPRAISAL_MASTER_EMP_IX ON HR_APPRAISAL_MASTER (EMPCODE);
CREATE INDEX HR_APPRAISAL_MASTER_ST_IX ON HR_APPRAISAL_MASTER (COMPC, STAGE);

-- Goals on one appraisal (copied corporate/department goals + the employee's own).
-- Ratings are 1–5; the latest reviewer's rating wins (HOD over RPT over self).
CREATE SEQUENCE HR_EMPLOYEE_GOAL_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_EMPLOYEE_GOAL (
  EMP_GOAL_ID   NUMBER          PRIMARY KEY,
  APPRAISAL_ID  NUMBER          NOT NULL REFERENCES HR_APPRAISAL_MASTER (APPRAISAL_ID),
  SOURCE        VARCHAR2(10)    NOT NULL CHECK (SOURCE IN ('CORPORATE','DEPARTMENT','INDIVIDUAL')),
  GOAL_ID       NUMBER          REFERENCES HR_GOAL_MASTER (GOAL_ID),
  OBJECTIVE     VARCHAR2(500)   NOT NULL,
  KPI_TEXT      VARCHAR2(300),
  TARGET        VARCHAR2(200),
  WEIGHTAGE     NUMBER(5,2)     NOT NULL CHECK (WEIGHTAGE > 0),
  DUE_DATE      DATE,
  ACHIEVEMENT   VARCHAR2(1000),
  SELF_RATING   NUMBER(1)       CHECK (SELF_RATING BETWEEN 1 AND 5),
  RPT_RATING    NUMBER(1)       CHECK (RPT_RATING BETWEEN 1 AND 5),
  HOD_RATING    NUMBER(1)       CHECK (HOD_RATING BETWEEN 1 AND 5),
  REMARKS       VARCHAR2(1000),
  SEQ           NUMBER(4)       DEFAULT 0 NOT NULL,
  CREATED_AT    DATE            DEFAULT SYSDATE,
  UPDATED_AT    DATE
);
CREATE INDEX HR_EMPLOYEE_GOAL_IX ON HR_EMPLOYEE_GOAL (APPRAISAL_ID);

-- KPI / competency lines copied from the template at launch.
