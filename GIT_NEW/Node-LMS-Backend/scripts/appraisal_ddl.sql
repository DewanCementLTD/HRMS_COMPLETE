  UPDATED_AT        DATE
);

-- One promotion evaluation per recommended appraisal.
CREATE SEQUENCE HR_PROMOTION_CASE_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_PROMOTION_CASE (
  CASE_ID            NUMBER          PRIMARY KEY,
  COMPC              NUMBER          NOT NULL,
  APPRAISAL_ID       NUMBER          NOT NULL REFERENCES HR_APPRAISAL_MASTER (APPRAISAL_ID),
  EMPCODE            VARCHAR2(30)    NOT NULL,
  CUR_DESG_CD        VARCHAR2(10),
  CUR_GRADE_CD       VARCHAR2(10),
  PROP_DESG_CD       VARCHAR2(10),
  PROP_GRADE_CD      VARCHAR2(10),
  RM_EMPCODE         VARCHAR2(30),
  HOD_MNO            VARCHAR2(30),
  STATUS             VARCHAR2(12)    DEFAULT 'ELIGIBILITY' NOT NULL
                     CHECK (STATUS IN ('ELIGIBILITY','COMPETENCY','MGR_RATING','HR_REVIEW','SIGNOFF','HOD_FINAL','CEO_FINAL',
                                       'APPROVED','REJECTED','NOT_ELIGIBLE','CANCELLED')),
  ELIGIBILITY_RESULT VARCHAR2(12)    DEFAULT 'INCOMPLETE' NOT NULL,
  ASSESS_DATE        DATE,
  ASSESSED_BY        VARCHAR2(30),
  EMP_COMMENTS       VARCHAR2(2000),
  TECH_TRAININGS     VARCHAR2(1000),
  SOFT_TRAININGS     VARCHAR2(1000),
  EMP_DECLARED_AT    DATE,
  MGR_RATED_BY       VARCHAR2(30),
  MGR_RATED_AT       DATE,
  COMP_SCORE         NUMBER(5,2),
  PERF_SCORE         NUMBER(5,2),
  COMP_WEIGHT_PCT    NUMBER(5,2),
  PERF_WEIGHT_PCT    NUMBER(5,2),
  OVERALL_SCORE      NUMBER(5,2),
  DECISION_BAND      VARCHAR2(60),
  DECISION_OUTCOME   VARCHAR2(13),
  HR_RECOMMENDATION  VARCHAR2(200),
  RATIONALE          VARCHAR2(2000),
  GAP_AREAS          VARCHAR2(1000),
  ACTIONS_TIMELINE   VARCHAR2(1000),
  NEXT_REVIEW_DATE   DATE,
  FINAL_DESG_CD      VARCHAR2(10),
  FINAL_GRADE_CD     VARCHAR2(10),
  NEW_PACKAGE        VARCHAR2(200),
  EFFECTIVE_DATE     DATE,
  DECIDED_AT         DATE,
  CREATED_BY         VARCHAR2(30),
  CREATED_AT         DATE            DEFAULT SYSDATE,
  UPDATED_BY         VARCHAR2(30),
  UPDATED_AT         DATE
);
CREATE UNIQUE INDEX HR_PROMOTION_CASE_UK ON HR_PROMOTION_CASE (APPRAISAL_ID);
CREATE INDEX HR_PROMOTION_CASE_ST_IX ON HR_PROMOTION_CASE (COMPC, STATUS);

-- Sheet 1: eligibility gate (filled by HR).
CREATE TABLE HR_PROMO_ELIGIBILITY (
  CASE_ID       NUMBER         NOT NULL REFERENCES HR_PROMOTION_CASE (CASE_ID),
  CRITERION     VARCHAR2(20)   NOT NULL,
  STATUS        CHAR(1)        CHECK (STATUS IN ('Y','N')),
  REMARKS       VARCHAR2(500),
  CONSTRAINT HR_PROMO_ELIGIBILITY_PK PRIMARY KEY (CASE_ID, CRITERION)
);

-- Sheet 2: competencies (employee self rating + manager rating, 1 to 5).
CREATE TABLE HR_PROMO_COMPETENCY (
  CASE_ID        NUMBER          NOT NULL REFERENCES HR_PROMOTION_CASE (CASE_ID),
  COMPETENCY_ID  NUMBER          NOT NULL,
  NAME           VARCHAR2(100)   NOT NULL,
  DEFINITION     VARCHAR2(1000),
  WEIGHT_PCT     NUMBER(5,2)     NOT NULL,
  SEQ            NUMBER(4)       DEFAULT 0 NOT NULL,
  SELF_RATING    NUMBER(1)       CHECK (SELF_RATING BETWEEN 1 AND 5),
  MGR_RATING     NUMBER(1)       CHECK (MGR_RATING BETWEEN 1 AND 5),
  EVIDENCE       VARCHAR2(1000),
  DEV_NEEDS      VARCHAR2(1000),
  MGR_COMMENT    VARCHAR2(1000),
  CONSTRAINT HR_PROMO_COMPETENCY_PK PRIMARY KEY (CASE_ID, COMPETENCY_ID)
);

-- Sheet 3: last 3 appraisal cycles (prefilled from HR_PERFORMANCE_HISTORY, edited by HR).
CREATE TABLE HR_PROMO_HISTORY (
  CASE_ID          NUMBER          NOT NULL REFERENCES HR_PROMOTION_CASE (CASE_ID),
  SEQ              NUMBER(1)       NOT NULL CHECK (SEQ BETWEEN 1 AND 3),
  APPRAISAL_YEAR   VARCHAR2(20),
  RATING_PCT       NUMBER(5,2),
  KPI_PCT          NUMBER(5,2),
  ACHIEVEMENTS     VARCHAR2(1000),
  CONSTRAINT HR_PROMO_HISTORY_PK PRIMARY KEY (CASE_ID, SEQ)
);

-- Sheet 5: independent recommendations and the final decisions.
CREATE SEQUENCE HR_PROMO_SIGNOFF_SEQ START WITH 1 NOCACHE;
CREATE TABLE HR_PROMO_SIGNOFF (
  SIGNOFF_ID   NUMBER          PRIMARY KEY,
  CASE_ID      NUMBER          NOT NULL REFERENCES HR_PROMOTION_CASE (CASE_ID),
  ROLE         VARCHAR2(10)    NOT NULL CHECK (ROLE IN ('RM','HOD','HR_HEAD','HOD_FINAL','CEO')),
  ACTOR        VARCHAR2(30)    NOT NULL,
  ACTOR_NAME   VARCHAR2(100),
  DECISION     VARCHAR2(20)    NOT NULL CHECK (DECISION IN ('RECOMMEND','NOT_RECOMMEND','APPROVE','REJECT','HOLD')),
  REMARKS      VARCHAR2(1000),
  ACTED_AT     DATE            DEFAULT SYSDATE NOT NULL
);
CREATE UNIQUE INDEX HR_PROMO_SIGNOFF_UK ON HR_PROMO_SIGNOFF (CASE_ID, ROLE);
