  CREATED_AT  DATE            DEFAULT SYSDATE,
  UPDATED_BY  VARCHAR2(30),
  UPDATED_AT  DATE,
  CHECK (LEVEL_TYPE = 'CORPORATE' OR DEPT_NO IS NOT NULL)
);
CREATE INDEX HR_GOAL_MASTER_IX ON HR_GOAL_MASTER (CYCLE_ID);

